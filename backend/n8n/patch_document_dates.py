#!/usr/bin/env python3
"""Format calendar dates consistently everywhere a document shows one.

The invoice renderers are generated by patch_invoice_template.py (it owns
issued_date/due_date). This script handles the two places that build their own
HTML:

  Render Receipt HTML                 - receipt dates, was ISO "2026-10-29"
  invoice-template-preview.json       - the sample invoice date in the chooser

Idempotent: skips a node that already carries fmtDate.

    python3 backend/n8n/patch_document_dates.py [--check]
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GW = ROOT / "backend" / "n8n" / "workflows" / "voice-gateway.json"
PREVIEW = ROOT / "backend" / "n8n" / "workflows" / "invoice-template-preview.json"

FMT = """const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
// Calendar dates only: Y-M-D in, "Oct 29, 2026" out. No timezone maths - a date
// column arrives as 00:00Z, and shifting it into local time prints the day before.
const fmtDate = (v) => {
  if (v === null || v === undefined || v === '') return '';
  const m = String(v).match(/^(\\d{4})-(\\d{2})-(\\d{2})/);
  return m ? `${MONTHS[Number(m[2]) - 1]} ${Number(m[3])}, ${m[1]}` : String(v);
};"""

OLD_RECEIPT_DATE = "const d = (v) => (v ? String(v).slice(0, 10) : '');"


def main():
    check = "--check" in sys.argv
    changes = []

    # --- receipt ------------------------------------------------------------
    gw = json.loads(GW.read_text())
    for n in gw["nodes"]:
        js = n.get("parameters", {}).get("jsCode") or ""
        if OLD_RECEIPT_DATE not in js:
            continue
        if "fmtDate =" in js:
            continue
        # Keep the call sites (d(...)) working by redefining d in terms of fmtDate.
        js = js.replace(OLD_RECEIPT_DATE, FMT + "\nconst d = (v) => fmtDate(v);", 1)
        n["parameters"]["jsCode"] = js
        changes.append(f"voice-gateway: {n['name']} receipt dates")

    # --- template preview sample -------------------------------------------
    prev = json.loads(PREVIEW.read_text())
    for n in prev["nodes"]:
        js = n.get("parameters", {}).get("jsCode") or ""
        if "issued_date" not in js or "fmtDate =" in js:
            continue
        if "const money" not in js:
            continue
        js = js.replace("const money", FMT + "\nconst money", 1)
        js = js.replace("issued_date: new Date().toISOString().slice(0, 10)",
                        "issued_date: fmtDate(new Date().toISOString())")
        js = js.replace("issued_date: new Date().toISOString().slice(0,10)",
                        "issued_date: fmtDate(new Date().toISOString())")
        n["parameters"]["jsCode"] = js
        changes.append(f"invoice-template-preview: {n['name']} sample date")

    print(f"{len(changes)} change(s)")
    for c in changes:
        print(f"  - {c}")
    if check:
        return 0
    if any(c.startswith("voice-gateway") for c in changes):
        GW.write_text(json.dumps(gw, indent=2, ensure_ascii=False) + "\n")
    if any(c.startswith("invoice-template-preview") for c in changes):
        PREVIEW.write_text(json.dumps(prev, indent=2, ensure_ascii=False) + "\n")
    if changes:
        print("written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
