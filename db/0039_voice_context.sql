-- 0039_voice_context.sql
-- Voice-call context store: one row per voice call, written twice.
--   1. at call start the hook inserts a 'pending' row carrying call_ref
--      (a uuid it also injects into assistantOverrides.variableValues, so the
--      end-of-call report comes back carrying the same ref -> deterministic
--      matching, no time-window guessing);
--   2. the Vapi end-of-call-report fills in transcript/ended_at and flips it
--      to 'reported'.
-- 'abandoned' = a call that started but never produced a report (never
-- connected, or Vapi lost it). Abandoned and pending rows are NEVER injected
-- as "the last conversation".
-- Retention is 10 days (nightly delete by created_at).

CREATE TABLE IF NOT EXISTS voice_calls (
    id               bigserial PRIMARY KEY,
    company_id       smallint NOT NULL DEFAULT 1 REFERENCES company_profile(id) ON DELETE CASCADE,
    call_ref         uuid NOT NULL,
    vapi_call_id     text UNIQUE,
    status           text NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'reported', 'abandoned')),
    started_at       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at         timestamptz,
    ended_reason     text,
    duration_seconds numeric(10, 2),
    summary          text,
    transcript       text,
    messages         jsonb,
    created_at       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS voice_calls_call_ref_key ON voice_calls (call_ref);
CREATE INDEX IF NOT EXISTS voice_calls_recent_idx
    ON voice_calls (company_id, ended_at DESC NULLS LAST);
CREATE INDEX IF NOT EXISTS voice_calls_created_idx
    ON voice_calls (created_at);

COMMENT ON TABLE voice_calls IS
    'Voice-call context (10-day retention). pending -> reported via the Vapi end-of-call-report; abandoned = no report ever arrived. Only reported rows are injected into the next call.';
COMMENT ON COLUMN voice_calls.call_ref IS
    'uuid generated by the call-start hook and injected as assistantOverrides.variableValues.call_ref; the end-of-call report echoes it back, which is how a report is matched to the call that started it.';
COMMENT ON COLUMN voice_calls.summary IS
    'Vapi analysis summary. NULL today (analysisPlan is unset on the assistant) — the injector falls back to the transcript tail.';
COMMENT ON COLUMN voice_calls.transcript IS
    'artifact.transcript ("AI: ... User: ..."). Only the tail is injected (context, not an archive).';
